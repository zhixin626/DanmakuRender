"""Fetch Claude review deltas for the user-authorized nightly work loop."""

from __future__ import annotations

import argparse
import json
import subprocess
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / "perf/tmp/night"
REPO = "zhixin626/DanmakuRender"


def gh_read(command):
    for attempt in range(3):
        try:
            return subprocess.check_output(command, cwd=ROOT, stderr=subprocess.PIPE)
        except subprocess.CalledProcessError:
            if attempt == 2:
                raise
            time.sleep(2)


def reviews(initialize=False):
    WORK.mkdir(parents=True, exist_ok=True)
    command = ["gh", "pr", "view", "1", "-R", REPO]
    rendered = gh_read([*command, "--comments"])
    (WORK / "pr_latest.md").write_bytes(rendered)
    data = json.loads(gh_read([*command, "--json", "comments"]))
    # Both clients can use the same account; the documented Claude signature,
    # rather than a shared GitHub login or a quoted mention, identifies review.
    signature = "_Generated by [Claude Code](https://claude.ai/code)_"
    comments = [
        item for item in data["comments"] if item["body"].rstrip().endswith(signature)
    ]
    state = WORK / "reviews.json"
    seen = (
        set(json.loads(state.read_text(encoding="utf8"))) if state.exists() else set()
    )
    new = [] if initialize else [item for item in comments if item["url"] not in seen]
    state.write_text(
        json.dumps(sorted(seen | {item["url"] for item in comments})), encoding="utf8"
    )
    return [{"url": item["url"], "body": item["body"]} for item in new]


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--init", action="store_true")
    args = parser.parse_args()
    print(json.dumps(reviews(args.init), ensure_ascii=False))
